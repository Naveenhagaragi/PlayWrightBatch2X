// Arithmetic Operators

let a = 10, b = 3;
console.log(a);
console.log(b);

let sum = a + b;  // + addition operator
let sub = a - b;  // - subtraction operator
let mul = a * b;  // * multiplication operator
let div = a / b;  // / division operator (returns quotient)
let rem = a % b;  // % modulus operator (returns remainder)  

console.log(sum);
console.log(sub);
console.log(mul);
console.log(div);
console.log(rem);